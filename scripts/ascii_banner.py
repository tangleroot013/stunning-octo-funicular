def banner() -> None:
    data = json.loads(Path("settings.json").read_text())
    name = data["repository"]["name"].upper()
    lines = [""] * 6
    for ch in name:
        glyph = FONT.get(ch, FONT[" "])
        for i, row in enumerate(glyph):
            lines[i] += row + "  "
    print("\n".join(lines))
    print(f"\n  {data['library']['package_name']} v{data['library']['version']}")

if __name__ == "__main__":
    banner()
